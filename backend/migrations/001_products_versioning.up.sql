ALTER SESSION SET DDL_LOCK_TIMEOUT = 10;

-- Passo 1: colunas anuláveis (alteração só de dicionário)
ALTER TABLE MCI_PRODUCTS ADD (
  UPDATED_AT  TIMESTAMP WITH TIME ZONE,
  ROW_VERSION NUMBER(10)
);

-- Passo 2: preencher linhas existentes
UPDATE MCI_PRODUCTS
   SET UPDATED_AT  = NVL(UPDATED_AT, CREATED_AT),
       ROW_VERSION = NVL(ROW_VERSION, 1)
 WHERE UPDATED_AT IS NULL OR ROW_VERSION IS NULL;
COMMIT;

-- Passo 3: defaults, NOT NULL e checagem
ALTER TABLE MCI_PRODUCTS MODIFY (
  UPDATED_AT  DEFAULT SYSTIMESTAMP NOT NULL,
  ROW_VERSION DEFAULT 1 NOT NULL
);
ALTER TABLE MCI_PRODUCTS ADD CONSTRAINT MCI_PRODUCTS_ROW_VERSION_CK CHECK (ROW_VERSION >= 1);

-- Passo 4: versão de preços (UPDATED_AT já existe em MCI_PRODUCT_PRICING)
ALTER TABLE MCI_PRODUCT_PRICING ADD (ROW_VERSION NUMBER(10));
UPDATE MCI_PRODUCT_PRICING SET ROW_VERSION = 1 WHERE ROW_VERSION IS NULL;
COMMIT;
ALTER TABLE MCI_PRODUCT_PRICING MODIFY (ROW_VERSION DEFAULT 1 NOT NULL);
ALTER TABLE MCI_PRODUCT_PRICING ADD CONSTRAINT MCI_PRODUCT_PRICING_ROW_VERSION_CK CHECK (ROW_VERSION >= 1);

-- Verificação pós-migration (deve retornar 0 e 0)
SELECT COUNT(*) FROM MCI_PRODUCTS WHERE UPDATED_AT IS NULL OR ROW_VERSION IS NULL;
SELECT COUNT(*) FROM MCI_PRODUCT_PRICING WHERE ROW_VERSION IS NULL;
